#ifndef FUNCS_H
#define FUNCS_H

#define MAX_SIZE 100

/**
 * @brief Знаходить найбільший елемент нижньої трикутної частини матриці.
 *
 * @details Переглядає головну діагональ квадратної матриці та всі елементи
 * нижче неї. Повертає максимальне значення та записує його індекси.
 * Якщо максимальних елементів декілька, повертає індекси першого з них.
 *
 * @param matrix Квадратна матриця цілих чисел.
 * @param N Розмір матриці (від 1 до MAX_SIZE).
 * @param max_row Вказівник на індекс рядка максимального елемента.
 * @param max_col Вказівник на індекс стовпця максимального елемента.
 * @return Максимальне значення в нижній трикутній частині матриці.
 */
int find_max_lower_triangle(int matrix[][MAX_SIZE], int N,
                            int *max_row, int *max_col);

#endif /* FUNCS_H */
